from __future__ import annotations

def craft_narration(battle: dict) -> str:
    """Arabic fallback when Gemini text quota fails."""
    name = battle["name_ar"]
    year = battle.get("year", "")
    sides = battle.get("sides", "")
    outcome = battle["outcome"]
    sources = battle.get("sources", "")

    text = (
        f"فِي قَلْبِ {year}، وَقَفَتْ {name} لِتَكُونَ وَاحِدَةً مِنْ تِلْكَ اللَّحَظَاتِ "
        f"الَّتِي لَا تَمُرُّ عَلَى التَّارِيخِ مُرُورَ الْكِرَامِ. عَلَى خَطِّ التَّمَاسِ بَيْنَ {sides}، "
        f"لَمْ يَكُنِ الْمَيْدَانُ مُجَرَّدَ أَرْضِ قِتَالٍ، بَلْ مَسْرَحاً تُحْسَمُ فِيهِ مَصَائِرُ دُوَلٍ وَأَجْيَالٍ.\n\n"
        f"بَدَأَتِ الْمَعْرَكَةُ بِتَوَتُّرٍ يَتَصَاعَدُ: اسْتِطْلَاعَاتٌ، وَتَحَشُّدَاتٌ، وَقَرَارَاتٌ لَا تَحْتَمِلُ التَّرَدُّدَ. "
        f"ثُمَّ انْفَتَحَ الِاشْتِبَاكُ عَلَى إِيقَاعِ السِّلَاحِ وَالْخُطَطِ؛ كَرٌّ وَفَرٌّ، وَمَوَاقِفُ صُمُودٍ أَوِ انْهِيَارٍ سَرِيعٍ، "
        f"حَتَّى بَاتَتْ نَتِيجَةُ الْيَوْمِ وَاضِحَةً لِلْجَمِيعِ: {outcome}.\n\n"
        f"مَا بَعْدَ الْمَيْدَانِ لَا يَقِلُّ أَهَمِّيَّةً عَمَّا جَرَى فِيهِ. فَالنَّتِيجَةُ أَعَادَتْ رَسْمَ الْخَرَائِطِ السِّيَاسِيَّةِ وَالْمَعْنَوِيَّةِ، "
        f"وَفَتَحَتْ بَاباً لِتَحَوُّلَاتٍ طَوِيلَةِ الْأَمَدِ مَا زَالَ الْمُؤَرِّخُونَ يَتَتَبَّعُونَ آثَارَهَا فِي الْمَصَادِرِ الْكِلَاسِيكِيَّةِ وَالْمَوْسُوعَاتِ.\n\n"
        f"هَكَذَا تُرْوَى {name}: لَيْسَتْ أَسْمَاءً جَامِدَةً فِي دَفْتَرٍ، بَلْ دِرَامَا بَشَرِيَّةٌ مُكْتَمِلَةُ الْعَنَاصِرِ؛ "
        f"قِيَادَةٌ، مُخَاطَرَةٌ، ثَمَنٌ بَاهِظٌ، وَنِهَايَةٌ تُكْتَبُ بِمِدَادِ الْوَاقِعِ لَا بِخَيَالِ الرُّوَاةِ.\n\n"
        f"المصادر: {sources}"
    )
    return text
